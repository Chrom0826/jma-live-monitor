              ctx.save();
              ctx.lineCap = 'square';
              ctx.beginPath();
              ctx.moveTo(epiX - 10, epiY - 10);
              ctx.lineTo(epiX + 10, epiY + 10);
              ctx.moveTo(epiX + 10, epiY - 10);
              ctx.lineTo(epiX - 10, epiY + 10);

