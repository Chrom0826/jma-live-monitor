interface CompiledGeoRing {
  normCoords: Float64Array; // High-res [normX0, normY0, normX1, normY1, ...]
  lodMedCoords: Float64Array; // Pre-decimated medium-LOD ring (6.2 <= zoom < 7.5)
  lodLowCoords: Float64Array; // Pre-decimated overview-LOD ring (zoom < 6.2 or moving)
  spanNorm: number; // Bounding-box span in normalized Mercator units for O(1) micro-island culling
}

interface CompiledGeoShape {
  id: string;
  divisionCode: string;
  prefId: number;
  severity: WarningSeverity;
  minNormX: number;
  minNormY: number;
  maxNormX: number;
  maxNormY: number;
  rings: CompiledGeoRing[];
  /** When present, the shape is traced from shared topology arcs (seamless, zoom-consistent LOD). */
  topo?: TopoShape;
}

function compileTopologyShapes(topo: JmaTopology): CompiledGeoShape[] {
  return topo.shapes.map((sh) => ({
    id: sh.id,
    divisionCode: sh.divisionCode,
    prefId: sh.prefId,
    severity: 'normal' as WarningSeverity,
    minNormX: sh.minNormX,
    minNormY: sh.minNormY,
    maxNormX: sh.maxNormX,
    maxNormY: sh.maxNormY,
    rings: [],
    topo: sh,
  }));
}

function decimateNormRing(
  src: Float64Array,
  minStepNorm: number
): Float64Array {
  const len = src.length;
  if (len <= 10 || minStepNorm <= 0) return src;
  const tmp = new Float64Array(len);
  let prevX = src[0];
  let prevY = src[1];
  tmp[0] = prevX;
  tmp[1] = prevY;
  let ptr = 2;
  const lastIdx = len - 2;
  for (let i = 2; i < lastIdx; i += 2) {
    const nx = src[i];
    const ny = src[i + 1];
    if (Math.abs(nx - prevX) + Math.abs(ny - prevY) < minStepNorm) {
      continue;
    }
    tmp[ptr++] = nx;
    tmp[ptr++] = ny;
    prevX = nx;
    prevY = ny;
  }
  tmp[ptr++] = src[lastIdx];
  tmp[ptr++] = src[lastIdx + 1];
  if (ptr < 8) return src;
  return tmp.slice(0, ptr);
}

function compileGeoJsonShapes(
  geoJson: any,
  extractMeta: (feature: any) => {
    id: string;
    divisionCode?: string;
    prefId?: number;
    severity?: WarningSeverity;
  },
  exteriorRingsOnly = false
): CompiledGeoShape[] {
  if (!geoJson || !Array.isArray(geoJson.features)) return [];
  const shapes: CompiledGeoShape[] = [];

  for (const f of geoJson.features) {
    const geom = f?.geometry;
    if (!geom) continue;
    const polys: number[][][][] =
      geom.type === 'Polygon'
        ? [geom.coordinates]
        : geom.type === 'MultiPolygon'
          ? geom.coordinates
          : [];
    if (polys.length === 0) continue;

    let minNormX = Infinity;
    let minNormY = Infinity;
    let maxNormX = -Infinity;
    let maxNormY = -Infinity;
    const rings: CompiledGeoRing[] = [];

    for (const poly of polys) {
      if (!Array.isArray(poly) || poly.length === 0) continue;
      const ringLimit = exteriorRingsOnly ? 1 : poly.length;
      for (let rIdx = 0; rIdx < ringLimit; rIdx++) {
        const rawRing = poly[rIdx];
        if (!Array.isArray(rawRing) || rawRing.length < 3) continue;
        const normCoords = new Float64Array(rawRing.length * 2);
        let ptr = 0;
        let rMinX = Infinity;
        let rMinY = Infinity;
        let rMaxX = -Infinity;
        let rMaxY = -Infinity;
        for (let i = 0; i < rawRing.length; i++) {
          const pt = rawRing[i];
          if (!Array.isArray(pt) || pt.length < 2) continue;
          const lon = Number(pt[0]);
          const lat = Number(pt[1]);
          if (Number.isNaN(lat) || Number.isNaN(lon)) continue;
          const { normX, normY } = latLonToNormMercator(lat, lon);
          normCoords[ptr++] = normX;
          normCoords[ptr++] = normY;
          if (normX < minNormX) minNormX = normX;
          if (normX > maxNormX) maxNormX = normX;
          if (normY < minNormY) minNormY = normY;
          if (normY > maxNormY) maxNormY = normY;
          if (normX < rMinX) rMinX = normX;
          if (normX > rMaxX) rMaxX = normX;
          if (normY < rMinY) rMinY = normY;
          if (normY > rMaxY) rMaxY = normY;
        }
        if (ptr >= 6) {
          const full =
            ptr === normCoords.length
              ? normCoords
              : normCoords.subarray(0, ptr);
          const highCoords = decimateNormRing(full, 0.4 / (256 * 512));
          const lodMedCoords = decimateNormRing(highCoords, 0.75 / (256 * 128));
          const lodLowCoords = decimateNormRing(lodMedCoords, 0.85 / (256 * 32));
          const spanNorm = Math.max(rMaxX - rMinX, rMaxY - rMinY);
          rings.push({
            normCoords: highCoords,
            lodMedCoords,
            lodLowCoords,
            spanNorm,
          });
        }
      }
    }

    if (rings.length > 0) {
      if (exteriorRingsOnly && rings.length > 1) {
        rings.sort((a, b) => b.spanNorm - a.spanNorm);
      }
      const meta = extractMeta(f);
      shapes.push({
        id: meta.id,
        divisionCode: meta.divisionCode || '',
        prefId: meta.prefId || 0,
        severity: meta.severity || 'normal',
        minNormX,
        minNormY,
        maxNormX,
        maxNormY,
        rings,
      });
    }
  }

  return shapes;
}

