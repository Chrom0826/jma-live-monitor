/**
 * Loads the pre-built, topology-preserving JMA warning-area map (`public/geo/jma-class20-topo.json`,
 * generated by `scripts/build-jma-topology.ts`). One ~400 KB (gzip) request replaces the 10 raw
 * `class20s_*.json` downloads (~3.1 MB) + `class10s.json` + runtime dissolve.
 * Falls back to the legacy runtime JMA GeoJSON path if the asset is unavailable.
 */
function loadJmaMunicipalityGeoJson(): Promise<{
  class20: any;
  class10: any;
  dissolvedDivisions: any;
  topology: JmaTopology | null;
}> {
  if (cachedJmaTopology) {
    return Promise.resolve({
      class20: cachedClass20GeoJson,
      class10: null,
      dissolvedDivisions: null,
      topology: cachedJmaTopology,
    });
  }
  if (class20FetchPromise) return class20FetchPromise;
  class20FetchPromise = fetch(
    `${import.meta.env.BASE_URL}geo/jma-class20-topo.json`
  )
    .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
    .then((file) => {
      const topo = decodeJmaTopology(file);
      for (const sh of topo.shapes) {
        if (sh.id && sh.labelPoint) cachedClass20LabelPoints[sh.id] = sh.labelPoint;
      }
      cachedJmaTopology = topo;
      return {
        class20: cachedClass20GeoJson,
        class10: null,
        dissolvedDivisions: null,
        topology: topo,
      };
    })
    .catch(() => {
      class20FetchPromise = null;
      return loadLegacyJmaMunicipalityGeoJson();
    });
  return class20FetchPromise;
}

function loadLegacyJmaMunicipalityGeoJson(): Promise<{
  class20: any;
  class10: any;
  dissolvedDivisions: any;
  topology: JmaTopology | null;
}> {
  if (
    cachedClass20GeoJson &&
    cachedClass10GeoJson &&
    cachedDissolvedDivisionsGeoJson
  ) {
    return Promise.resolve({
      class20: cachedClass20GeoJson,
      class10: cachedClass10GeoJson,
      dissolvedDivisions: cachedDissolvedDivisionsGeoJson,
      topology: null,
    });
  }
  if (class20FetchPromise) return class20FetchPromise;

  class20FetchPromise = Promise.all([
    Promise.all(
      Array.from({ length: 10 }, (_, idx) =>
        fetch(
          `https://www.jma.go.jp/bosai/common/const/geojson/class20s_${idx}.json`
        )
          .then((r) => (r.ok ? r.json() : null))
          .catch(() => null)
      )
    ),
    fetch('https://www.jma.go.jp/bosai/common/const/geojson/class10s.json')
      .then((r) => (r.ok ? r.json() : null))
      .catch(() => null),
    fetchSharedJmaAreaConst(),
  ]).then(([c20Parts, c10Json, areaJson]) => {
    const validParts = c20Parts.filter(
      (p) => p && Array.isArray(p.features)
    );
    if (validParts.length > 0) {
      const allFeatures = validParts.flatMap((p) => p.features);
      for (const f of allFeatures) {
        const code = String(f?.properties?.code || '');
        const divMeta =
          code && code !== 'hoppo'
            ? resolveWarningDivision(code, areaJson)
            : null;
        if (f.properties) {
          f.properties.divisionCode = divMeta?.code || (code === 'hoppo' ? 'hoppo' : '');
          f.properties.prefId = divMeta?.prefId || Number(code.slice(0, 2)) || 0;
        }
        const lp = f?.properties?.labelPoints?.[0];
        if (code && Array.isArray(lp) && lp.length >= 2) {
          const lon = Number(lp[0]);
          const lat = Number(lp[1]);
          if (!Number.isNaN(lat) && !Number.isNaN(lon)) {
            cachedClass20LabelPoints[code] = [lat, lon];
          }
        }
      }
      cachedClass20GeoJson = {
        type: 'FeatureCollection',
        features: allFeatures,
      };
    }
    if (c10Json && Array.isArray(c10Json.features)) {
      cachedClass10GeoJson = c10Json;
      // Topologically dissolve the 153 `class10s` sub-regions into the 57 JMA Warning Divisions
      // (`宗谷`, `上川・留萌`, `網走・北見・紋別`, `石狩・空知・後志`, `胆振・日高`, `釧路・根室・十勝`, `渡島・檜山`, `[各都府県]`, `奄美`, `沖縄4地方`)
      // so every prefecture and Hokkaido division is 100% unified with zero internal sub-boundaries!
      cachedDissolvedDivisionsGeoJson = dissolveGeoJsonByGroup(
        c10Json.features,
        (f) => {
          const code = String(f?.properties?.code || '');
          if (!code) return null;
          if (code === 'hoppo') return 'hoppo';
          const divMeta = resolveWarningDivision(code, areaJson);
          return divMeta?.code || code;
        }
      );
    }
    return {
      class20: cachedClass20GeoJson,
      class10: cachedClass10GeoJson,
      dissolvedDivisions: cachedDissolvedDivisionsGeoJson,
      topology: null,
    };
  });

  return class20FetchPromise;
}

/**
 * Fast Web Mercator projection from (lat, lon) at fractional zoom level.
 * Matches `L.CRS.EPSG3857.latLngToPoint(L.latLng(lat, lon), zoom)` without object allocation.
 */
const DEG_TO_RAD = Math.PI / 180;
const MAX_MERCATOR_LAT = 85.0511287798;

function latLonToNormMercator(
  lat: number,
  lon: number
): { normX: number; normY: number } {
  const clampedLat = Math.max(
    -MAX_MERCATOR_LAT,
    Math.min(MAX_MERCATOR_LAT, lat)
  );
  const sin = Math.sin(clampedLat * DEG_TO_RAD);
  const normX = lon / 360 + 0.5;
  const normY = 0.5 - Math.log((1 + sin) / (1 - sin)) / (4 * Math.PI);
  return { normX, normY };
}

function normMercatorToLatLon(
  normX: number,
  normY: number
): { lat: number; lon: number } {
  const lon = (normX - 0.5) * 360;
  const y2 = (0.5 - normY) * (4 * Math.PI);
  const expY2 = Math.exp(y2);
  const sin = (expY2 - 1) / (expY2 + 1);
  const lat = Math.asin(sin) / DEG_TO_RAD;
  return { lat, lon };
}

function projectLatLonToWorldPx(
  lat: number,
  lon: number,
  scale: number
): { x: number; y: number } {
  const { normX, normY } = latLonToNormMercator(lat, lon);
  return { x: normX * scale, y: normY * scale };
}

interface CompiledGeoRing {
  normCoords: Float64Array; // High-res [normX0, normY0, normX1, normY1, ...]
  lodMedCoords: Float64Array; // Pre-decimated medium-LOD ring (6.2 <= zoom < 7.5)
  lodLowCoords: Float64Array; // Pre-decimated overview-LOD ring (zoom < 6.2 or moving)
  spanNorm: number; // Bounding-box span in normalized Mercator units for O(1) micro-island culling
}

interface CompiledGeoShape {
  id: string;
  divisionCode: string;
  prefId: number;
  severity: WarningSeverity;
  minNormX: number;
  minNormY: number;
  maxNormX: number;
  maxNormY: number;
  rings: CompiledGeoRing[];
  /** When present, the shape is traced from shared topology arcs (seamless, zoom-consistent LOD). */
  topo?: TopoShape;
}

function compileTopologyShapes(topo: JmaTopology): CompiledGeoShape[] {
  return topo.shapes.map((sh) => ({
    id: sh.id,
    divisionCode: sh.divisionCode,
    prefId: sh.prefId,
    severity: 'normal' as WarningSeverity,
    minNormX: sh.minNormX,
    minNormY: sh.minNormY,
    maxNormX: sh.maxNormX,
    maxNormY: sh.maxNormY,
    rings: [],
    topo: sh,
  }));
}

function decimateNormRing(
  src: Float64Array,
  minStepNorm: number
): Float64Array {
  const len = src.length;
  if (len <= 10 || minStepNorm <= 0) return src;
  const tmp = new Float64Array(len);
  let prevX = src[0];
  let prevY = src[1];
  tmp[0] = prevX;
  tmp[1] = prevY;
  let ptr = 2;
  const lastIdx = len - 2;
  for (let i = 2; i < lastIdx; i += 2) {
    const nx = src[i];
    const ny = src[i + 1];
    if (Math.abs(nx - prevX) + Math.abs(ny - prevY) < minStepNorm) {
      continue;
    }
    tmp[ptr++] = nx;
    tmp[ptr++] = ny;
    prevX = nx;
    prevY = ny;
  }
  tmp[ptr++] = src[lastIdx];
  tmp[ptr++] = src[lastIdx + 1];
  if (ptr < 8) return src;
  return tmp.slice(0, ptr);
}

function compileGeoJsonShapes(
  geoJson: any,
  extractMeta: (feature: any) => {
    id: string;
    divisionCode?: string;
    prefId?: number;
    severity?: WarningSeverity;
  },
  exteriorRingsOnly = false
): CompiledGeoShape[] {
  if (!geoJson || !Array.isArray(geoJson.features)) return [];
  const shapes: CompiledGeoShape[] = [];

  for (const f of geoJson.features) {
    const geom = f?.geometry;
    if (!geom) continue;
    const polys: number[][][][] =
      geom.type === 'Polygon'
        ? [geom.coordinates]
        : geom.type === 'MultiPolygon'
          ? geom.coordinates
          : [];
    if (polys.length === 0) continue;

    let minNormX = Infinity;
    let minNormY = Infinity;
    let maxNormX = -Infinity;
    let maxNormY = -Infinity;
    const rings: CompiledGeoRing[] = [];

    for (const poly of polys) {
      if (!Array.isArray(poly) || poly.length === 0) continue;
      const ringLimit = exteriorRingsOnly ? 1 : poly.length;
      for (let rIdx = 0; rIdx < ringLimit; rIdx++) {
        const rawRing = poly[rIdx];
        if (!Array.isArray(rawRing) || rawRing.length < 3) continue;
        const normCoords = new Float64Array(rawRing.length * 2);
        let ptr = 0;
        let rMinX = Infinity;
        let rMinY = Infinity;
        let rMaxX = -Infinity;
        let rMaxY = -Infinity;
        for (let i = 0; i < rawRing.length; i++) {
          const pt = rawRing[i];
          if (!Array.isArray(pt) || pt.length < 2) continue;
          const lon = Number(pt[0]);
          const lat = Number(pt[1]);
          if (Number.isNaN(lat) || Number.isNaN(lon)) continue;
          const { normX, normY } = latLonToNormMercator(lat, lon);
          normCoords[ptr++] = normX;
          normCoords[ptr++] = normY;
          if (normX < minNormX) minNormX = normX;
          if (normX > maxNormX) maxNormX = normX;
          if (normY < minNormY) minNormY = normY;
          if (normY > maxNormY) maxNormY = normY;
          if (normX < rMinX) rMinX = normX;
          if (normX > rMaxX) rMaxX = normX;
          if (normY < rMinY) rMinY = normY;
          if (normY > rMaxY) rMaxY = normY;
        }
        if (ptr >= 6) {
          const full =
            ptr === normCoords.length
              ? normCoords
              : normCoords.subarray(0, ptr);
          const highCoords = decimateNormRing(full, 0.4 / (256 * 512));
          const lodMedCoords = decimateNormRing(highCoords, 0.75 / (256 * 128));
          const lodLowCoords = decimateNormRing(lodMedCoords, 0.85 / (256 * 32));
          const spanNorm = Math.max(rMaxX - rMinX, rMaxY - rMinY);
          rings.push({
            normCoords: highCoords,
            lodMedCoords,
            lodLowCoords,
            spanNorm,
          });
        }
      }
    }

    if (rings.length > 0) {
      if (exteriorRingsOnly && rings.length > 1) {
        rings.sort((a, b) => b.spanNorm - a.spanNorm);
      }
      const meta = extractMeta(f);
      shapes.push({
        id: meta.id,
        divisionCode: meta.divisionCode || '',
        prefId: meta.prefId || 0,
        severity: meta.severity || 'normal',
        minNormX,
        minNormY,
        maxNormX,
        maxNormY,
        rings,
      });
    }
  }

  return shapes;
}

